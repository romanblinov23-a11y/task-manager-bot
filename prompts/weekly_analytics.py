import json

from prompts.client import ask_claude

# Промпт 3 — PROJECT_SPEC.md, раздел 8.3
_PROMPT_TEMPLATE = """Ты — аналитический модуль еженедельной отчётности для бота-менеджера
проектов Романа. Тебе передана статистика за неделю по трём проектам:
Парк Горького, Окко, Аврора. Твоя задача — написать короткие,
содержательные наблюдения по каждому проекту отдельно, а затем дать
сводку по сотрудникам, занятым в нескольких проектах одновременно.
БЕЗ итоговых оценок или баллов эффективности — только факты и
наблюдения по фактам.

ДАННЫЕ ПО ПРОЕКТАМ
{projects_stats_json}

Структура входных данных — массив из трёх объектов, каждый содержит:
- project_name
- employee_stats: для каждого сотрудника (с assignee_telegram_id) —
  задач в работе, закрыто за неделю, просрочено, переносов за
  неделю, причины переносов, запросов помощи
- task_stats: задачи с 2+ переносами, задачи без обновления статуса
  дольше {stale_days} дней, задачи с близким сроком без прогресса

ДАННЫЕ ПО СОТРУДНИКАМ С НЕСКОЛЬКИМИ ПРОЕКТАМИ
{multi_project_employees_json}
(заранее посчитано кодом: список сотрудников, которые встречаются
в employee_stats более чем одного проекта, с разбивкой их цифр по
каждому проекту, в котором они заняты)

ЧТО НУЖНО СДЕЛАТЬ ДЛЯ КАЖДОГО ПРОЕКТА ОТДЕЛЬНО

1. Короткая сводка по проекту в целом (сколько задач закрыто/в работе/
   просрочено суммарно за неделю)

2. По каждому сотруднику этого проекта — 1-2 предложения наблюдения
   на основе его цифр. Если переносы повторяются по одной причине —
   укажи это явно (это сигнал о внешней проблеме, а не о сотруднике).
   Не делай выводов о личных качествах сотрудника, только описывай
   паттерн в фактах.

3. Раздел "Задачи, требующие внимания" — только по задачам ЭТОГО
   проекта, с кратким пояснением, в чём проявляется застой

4. Не присваивай числовые оценки или рейтинги — только описание
   ситуации

НЕ СМЕШИВАЙ ПРОЕКТЫ МЕЖДУ СОБОЙ. Каждый проект — самостоятельный
раздел отчёта.

ЧТО НУЖНО СДЕЛАТЬ ДЛЯ СВОДКИ ПО МНОГОПРОЕКТНЫМ СОТРУДНИКАМ

Для каждого сотрудника из multi_project_employees_json — короткая
сводка (2-3 предложения): в каких проектах занят, какая суммарная
нагрузка (общее число задач в работе по всем проектам), и есть ли
заметный перекос (например, в одном проекте всё закрывается вовремя,
а в другом — постоянные переносы). Если нагрузка распределена
равномерно и без проблем — так и скажи коротко, не нужно искать
проблему, если её нет.

Если таких сотрудников нет — пропусти этот раздел целиком, не пиши
"сотрудников с несколькими проектами не найдено".

ФОРМАТ ОТВЕТА
Обычный текст (НЕ JSON), готовый для отправки в Telegram:

🏢 ПАРК ГОРЬКОГО
Сводка: [N закрыто, N в работе, N просрочено]

По сотрудникам:
[Имя] — [наблюдение]

Задачи, требующие внимания:
- [задача] — [что не так]

🏢 ОККО
[аналогично]

🏢 АВРОРА
[аналогично]

👥 СОТРУДНИКИ В НЕСКОЛЬКИХ ПРОЕКТАХ
[Имя] — [сводка по нагрузке и перекосам между проектами]"""


def generate_weekly_report(
    projects_stats: list[dict],
    multi_project_employees: list[dict],
    stale_days: int = 5,
) -> str:
    """Промпт 3: формулирует еженедельный текстовый отчёт по уже
    посчитанным кодом агрегатам (раздел 7)."""
    prompt = (
        _PROMPT_TEMPLATE
        .replace("{projects_stats_json}", json.dumps(projects_stats, ensure_ascii=False, indent=2))
        .replace("{multi_project_employees_json}", json.dumps(multi_project_employees, ensure_ascii=False, indent=2))
        .replace("{stale_days}", str(stale_days))
    )
    return ask_claude(prompt, max_tokens=4096).strip()
